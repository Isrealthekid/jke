// Builds the Playground page's media.
//
//   Source files live in   playground-src/Designs/<Client>/<Campaign>/1.png, 2.png ...
//                          playground-src/Motion/<anything>.mp4
//   Running `npm run playground` turns them into web-ready files in public/playground/
//   and writes data/playground.ts (the list the page reads), so nothing needs the file system
//   at runtime (the live site can't read folders).
//
// To add work: drop a new campaign folder (or a video) into playground-src and run the command.

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const sharp = require("sharp");

const ROOT = process.cwd();
const SRC = path.join(ROOT, "playground-src");
const OUT = path.join(ROOT, "public", "playground");

const collator = new Intl.Collator("en", { numeric: true, sensitivity: "base" });
const slug = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
const tidy = (s) => s.replace(/_t\b/g, "’t").replace(/_/g, " ").trim();
const CLIENT_NAMES = { JoieTheSMM: "Joie The SMM" };

const dirs = (p) =>
  fs.existsSync(p)
    ? fs
        .readdirSync(p, { withFileTypes: true })
        .filter((d) => d.isDirectory())
        .map((d) => d.name)
        .sort(collator.compare)
    : [];
const files = (p, exts) =>
  fs
    .readdirSync(p)
    .filter((f) => exts.includes(path.extname(f).toLowerCase()))
    .sort(collator.compare);

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const carousels = [];
const designsRoot = path.join(SRC, "Designs");
for (const client of dirs(designsRoot)) {
  for (const campaign of dirs(path.join(designsRoot, client))) {
    const dir = path.join(designsRoot, client, campaign);
    const id = `${slug(client)}-${slug(campaign)}`;
    fs.mkdirSync(path.join(OUT, id), { recursive: true });
    const slides = [];
    for (const f of files(dir, [".png", ".jpg", ".jpeg", ".webp"])) {
      const name = `${slug(path.basename(f, path.extname(f)))}.webp`;
      const info = await sharp(path.join(dir, f))
        .resize({ width: 1080, withoutEnlargement: true })
        .webp({ quality: 82 })
        .toFile(path.join(OUT, id, name));
      slides.push({ src: `/playground/${id}/${name}`, w: info.width, h: info.height });
    }
    if (slides.length)
      carousels.push({
        id,
        client: CLIENT_NAMES[client] ?? client,
        title: tidy(campaign),
        slides,
      });
  }
}

const probe = (file) => {
  try {
    const out = execFileSync(
      "ffprobe",
      ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "csv=p=0", file],
      { encoding: "utf8" }
    ).trim();
    const [w, h] = out.split(",").map(Number);
    if (w && h) return { w, h };
  } catch {}
  return { w: 1920, h: 1080 };
};
const poster = (file, dest) => {
  try {
    execFileSync("ffmpeg", ["-y", "-v", "error", "-ss", "0.6", "-i", file, "-frames:v", "1", "-q:v", "3", dest]);
    return true;
  } catch {
    return false;
  }
};

const motion = [];
const motionRoot = path.join(SRC, "Motion");
if (fs.existsSync(motionRoot)) {
  fs.mkdirSync(path.join(OUT, "motion"), { recursive: true });
  for (const f of files(motionRoot, [".mp4", ".webm", ".mov"])) {
    const base = path.basename(f, path.extname(f));
    const id = slug(base);
    const dest = path.join(OUT, "motion", id + path.extname(f).toLowerCase());
    fs.copyFileSync(path.join(motionRoot, f), dest);
    const { w, h } = probe(dest);
    const hasPoster = poster(dest, path.join(OUT, "motion", id + ".jpg"));
    motion.push({
      id,
      title: tidy(base).replace(/\s+with sound$/i, ""),
      src: `/playground/motion/${id}${path.extname(f).toLowerCase()}`,
      poster: hasPoster ? `/playground/motion/${id}.jpg` : undefined,
      w,
      h,
      sound: /with sound/i.test(base),
    });
  }
}

const ts = `// Generated by scripts/build-playground.mjs. Run \`npm run playground\` after adding work to playground-src.

export interface PlaygroundSlide {
  src: string;
  w: number;
  h: number;
}

export interface PlaygroundCarousel {
  id: string;
  client: string;
  title: string;
  slides: PlaygroundSlide[];
}

export interface PlaygroundMotion {
  id: string;
  title: string;
  src: string;
  poster?: string;
  w: number;
  h: number;
  sound: boolean;
}

export const carousels: PlaygroundCarousel[] = ${JSON.stringify(carousels, null, 2)};

export const motion: PlaygroundMotion[] = ${JSON.stringify(motion, null, 2)};
`;
fs.writeFileSync(path.join(ROOT, "data", "playground.ts"), ts);
console.log(`${carousels.length} carousels, ${carousels.reduce((n, c) => n + c.slides.length, 0)} slides, ${motion.length} motion pieces`);
